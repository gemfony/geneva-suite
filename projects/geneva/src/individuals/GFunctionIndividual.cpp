/******************************************************************************/
/**
 * @brief Builds the flat genome's STRUCTURE only.
 *
 * The five parameter-type modes differ in constrained-vs-unbounded and
 * whether the parameters share one adaption group (a *collection*) or each carry their own (a collection
 * of *objects* / individual objects). The configured Gauss / bi-Gauss adaptor settings live on the
 * OA-owned config (see buildAdaptionConfig()), not in the genome layout. The start value is the lower
 * perimeter; the optimization algorithm random-initialises within [min, max].
 *
 * @param c The Config supplying the parameter dimension (par_dim), the init range (min_var, max_var) and the parameter-object type (p_t)
 * @return The flat genome structure (GenomeData) for the selected parameter type
 */
gen::GenomeData GFunctionIndividual::buildGenome(const Config &c) {
    const std::size_t n_data = c.par_dim;
    const double min_v = c.min_var;
    const double max_v = c.max_var;

    gen::GGenomeBuilder b;
    switch(c.p_t) {
    case parameterType::UNBOUNDED_SHARED: { // unbounded, one shared group
        b.addDoublePlainGroup(n_data, min_v, max_v);
    } break;

    case parameterType::BOUNDED_SHARED: { // bounded, one shared group
        b.addDoubleGroup(n_data, min_v, max_v);
    } break;

    case parameterType::UNBOUNDED_PER_PARAMETER: { // unbounded, a group per parameter
        for(std::size_t i = 0; i < n_data; i++) {
            b.addDouble(min_v).perimeter(min_v, max_v);
        }
    } break;

    case parameterType::BOUNDED_PER_PARAMETER: { // bounded, a group per parameter
        for(std::size_t i = 0; i < n_data; i++) {
            b.addDouble(min_v, min_v, max_v);
        }
    } break;

    default: {
        throw geneva_exception(
            g_error_streamer(DO_LOG, Gem::Common::timeAndPlace())
            << "In GFunctionIndividual::buildGenome(): Error!"
            << "Found invalid parameter_type: " << c.p_t << '\n'
        );
    }
    }

    return b.build();
}

/******************************************************************************/
/**
 * @brief Builds the OA-owned adaption configuration for a genome produced by this factory.
 *
 * Every double group (one shared group for the collection modes, one per parameter for the object
 * modes) receives the configured single-Gauss or bi-Gauss adaptor.
 *
 * @param sample A sample flat genome whose group structure the adaption config is built against
 * @param c The Config supplying the adaptor parameters (sigmas, ad_prob, bi-gaussian flag, ...)
 * @return A shared pointer to the populated OA-owned adaption configuration
 */
//! [adaptors-build-config]
std::shared_ptr<OptimizationAlgorithms::GAdaptionConfigBase>
GFunctionIndividual::buildAdaptionConfig(const gen::GGenome &sample, const Config &c) {
    namespace oa = Gem::Geneva::OptimizationAlgorithms;
    auto cfg = oa::makeAdaptionConfig<oa::GAdaptionConfigBase>(sample);
    for(std::size_t i = 0; i < cfg->doubleGroups().size(); i++) {
        if(c.use_bi_gaussian) {
            cfg->groupDouble(i).biGauss(
                c.sigma1, c.sigma_sigma1, c.min_sigma1, c.max_sigma1,
                c.sigma2, c.sigma_sigma2, c.min_sigma2, c.max_sigma2,
                c.delta, c.sigma_delta, c.min_delta, c.max_delta,
                c.ad_prob, /* use_symmetric_sigmas = */ false, c.adapt_ad_prob,
                c.adaption_threshold
            );
        }
        else {
            cfg->groupDouble(i).gauss(
                c.sigma1, c.sigma_sigma1, c.min_sigma1, c.max_sigma1,
                c.ad_prob, c.adapt_ad_prob, c.adaption_threshold,
                Gem::Geneva::adaptionMode::WITHPROBABILITY, c.min_ad_prob, c.max_ad_prob
            );
        }
    }
    return cfg;
}
