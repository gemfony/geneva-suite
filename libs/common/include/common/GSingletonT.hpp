namespace Gem::Common {

/******************************************************************************/
/**
 * @brief This function creates a new T object. It can be specialized by the object
 * used inside of Gemfony's singleton, e.g. in case they do not have a default
 * constructor or wish to perform special actions prior to initialization.
 *
 * @tparam T The type of the object to be created
 * @return A std::shared_ptr to a newly created T object
 */
template <typename T> std::shared_ptr<T> TFactory_GSingletonT() {
    return std::make_shared<T>();
}

/******************************************************************************/
/**
 * Opt-in lifetime trait for GSingletonT. Specialise to std::true_type for
 * singleton types that must NOT be destroyed at program shutdown — typically
 * those logged-to or otherwise used during static destruction, where the
 * destruction order against other statics and still-running threads is
 * unspecified. A never-destroy singleton is pinned by a single leaked owning
 * reference in instance() and is reclaimed only by the OS at process exit;
 * GSingletonT::reset() is disabled for such types (it would orphan the pinned
 * instance and break the singleton invariant). Leave the default
 * (std::false_type) for singletons whose destructor must run, e.g. those that
 * join threads or release OS resources (such as GRandomFactory).
 *
 * @tparam T The singleton payload type whose shutdown-lifetime policy is being declared
 */
template <typename T>
struct gsingleton_never_destroy : std::false_type {};

/******************************************************************************/
/**
 * This class implements a singleton pattern, augmented so that it returns
 * a std::shared_ptr. This allows other singletons to store a shared_ptr to
 * T, so that it only gets destroyed once it is no longer needed. Note that
 * the static shared_ptr may long have vanished at that time.
 *
 * @tparam T The type of the singleton payload object handed out by instance()
 */
template <typename T>
class GSingletonT {
public:
    /***************************************************************************/
    // Deleted constructors, destructor and assignment operators. This class is
    // not meant to be instantiable.
    GSingletonT() = delete;
    GSingletonT(GSingletonT<T> const &) = delete;
    GSingletonT(GSingletonT<T> &&) = delete;
    ~GSingletonT() = delete;

    GSingletonT<T> &operator=(GSingletonT<T> const &) = delete;
    GSingletonT<T> &operator=(GSingletonT<T> &&) = delete;

    /***************************************************************************/

    using STYPE = T;

    /***************************************************************************/
    /**
	  * @brief Returns the singleton instance, creating it on first access. It is handed
	  * out as a std::shared_ptr so other objects may keep it alive past this
	  * static's own destruction, which fixes inter-singleton destruction order.
	  *
	  * @return A std::shared_ptr to the (lazily created) singleton instance of T
	  */
    [[nodiscard]] static std::shared_ptr<T> instance() {
        storage_type &s = storage();
        // Load once into a local. An implicit `if(not s.p)` on the atomic would
        // construct-and-destroy a temporary shared_ptr (extra refcount round-trip)
        // on every check; loading into `sp` once covers both checks and the return.
        auto sp = s.p.load();
        if(not sp) {
            // Prevent concurrent "first" access. Re-check under the lock: another
            // thread may have completed initialisation between our unlocked load
            // and our acquisition of the mutex.
            std::scoped_lock const lk(s.creation_mutex);
            sp = s.p.load();
            if(not sp) {
                sp = Gem::Common::TFactory_GSingletonT<T>();
                s.p.store(sp);
                if constexpr(gsingleton_never_destroy<T>::value) {
                    // Never-destroy singletons must outlive every other static
                    // (they are logged-to / used during static destruction).
                    // Pin the instance with one owning reference that is
                    // deliberately leaked: the refcount can then never reach
                    // zero, so T is never destroyed and is reclaimed only by
                    // the OS at process exit. The raw pointer is parked in a
                    // function-local static so the allocation stays reachable
                    // (LSan reports it as still-reachable, not as a leak). This
                    // branch runs once, under creation_mutex.
                    static auto *const keep_alive =
                        new std::shared_ptr<T>(sp);
                    (void) keep_alive;
                }
            }
        }
        return sp;
    }

    /***************************************************************************/
    /**
	  * @brief Drops the stored instance so the next instance() call creates a fresh one.
	  * Disabled for never-destroy singletons (see gsingleton_never_destroy): for
	  * those, resetting would leave the leaked pin pointing at an orphaned
	  * instance while instance() builds a second one, breaking uniqueness.
	  * Calling reset() on such a type is therefore a compile error.
	  *
	  * @tparam U Defaulted to T; exists only so the requires-clause can disable reset()
	  *           for never-destroy types. Must not be supplied explicitly.
	  */
    template <typename U = T>
    static void reset()
        requires(not gsingleton_never_destroy<U>::value)
    {
        static_assert(std::is_same_v<U, T>,
                      "GSingletonT::reset() does not take an explicit template argument");
        storage_type &s = storage();
        // Reset must be ordered against any in-flight instance() initialiser:
        // without this lock, an initialiser could store the freshly-built
        // singleton AFTER our reset, silently undoing it.
        std::scoped_lock const lk(s.creation_mutex);
        s.p.store(nullptr);
    }

private:
    /***************************************************************************/
    /**
	  * Storage shared by instance() and reset(). The atomic makes the unlocked
	  * first check in instance() a well-defined load instead of a data race
	  * against the locked init / reset writes.
	  */
    struct storage_type {
        std::atomic<std::shared_ptr<T>> p;
        std::mutex creation_mutex;
    };

    /**
     * @brief Returns the function-local static storage, lazily constructed on first call.
     *
     * @return A reference to the single storage_type instance backing this singleton
     */
    static storage_type &storage() {
        static storage_type s;
        return s;
    }

    /***************************************************************************/
};

/******************************************************************************/

} /* namespace Gem::Common */
