/**
 * The serialization modes that are currently allowed. The two GArchive (Weft) codecs are the only
 * modes; the numeric values 3/4 are retained (rather than renumbered to 0/1) so configuration files
 * carry stable mode values -- values 0-2 belonged to the removed Boost.Serialization text/XML/binary
 * archives and are simply no longer valid.
 */
enum class serializationMode : Gem::Common::ENUMBASETYPE {
    GEM_BINARY = 3, ///< GArchive flat little-endian binary codec (the networked-wire default)
    GEM_JSON = 4    ///< GArchive self-describing JSON codec (the checkpoint default)
};

/** @brief Every serialization mode there is: the one list help texts and the parser read */
inline constexpr std::array<serializationMode, 2> SERIALIZATIONMODES{
    serializationMode::GEM_BINARY,
    serializationMode::GEM_JSON
};

/**
 * @brief serializationMode streams as its underlying numeric value (see numeric_enum_values_v); a
 * value that names no mode (one of the removed Boost archives, say) fails the stream, so that an
 * option or a configuration that names one is refused where it is read
 */
template <>
inline constexpr auto numeric_enum_values_v<serializationMode> = SERIALIZATIONMODES;

/**
 * @brief The modes for a help text, from SERIALIZATIONMODES: "GEM_BINARY (3) or GEM_JSON (4)"
 */
[[nodiscard]] std::string serializationModeChoices();

/**
 * @brief Converts a serializationMode to a string representation for debugging purposes.
 */
[[nodiscard]] std::string serModeToString(Gem::Common::serializationMode ser_mod);

