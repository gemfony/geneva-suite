/**
 * Opt-in numeric stream insertion/extraction for Geneva's enum classes (needed
 * for streaming / Gem::Common::fromString<>).
 *
 * Nearly every Geneva enum streams as its underlying numeric value; the
 * operator bodies used to be copy-pasted per enum across all libraries. An enum
 * now opts in by specializing the variable template below with the list of its
 * valid values (in namespace Gem::Common, right next to the enum's definition),
 * and the two constrained operator templates that follow supply the one shared
 * implementation. The reader refuses a number that is none of the listed values
 * (it fails the stream), so a configuration value or an option such as "7" for
 * a two-valued enum is refused where it is read instead of becoming an
 * enumerator that does not exist. A contiguous enum lists its values with
 * numeric_enum_range(); one with gaps lists them one by one. A namespace other
 * than Gem::Common additionally re-exports the operators once via
 * using-declarations so that ADL finds them for its own enums (see e.g.
 * GPlotEnums.hpp).
 *
 * Enums with textual (non-numeric) streaming -- Gem::Common::tribool, and
 * such enums of the libraries above common -- simply do not opt in and keep
 * their hand-written operators.
 *
 * @code
 * template <> inline constexpr auto numeric_enum_values_v<sortOrder>
 *     = numeric_enum_range<sortOrder::LOWERISBETTER, sortOrder::HIGHERISBETTER>();
 * @endcode
 */
template <typename enum_type>
inline constexpr auto numeric_enum_values_v = std::array<enum_type, 0>{};

/** @brief Satisfied by enum types that opted into numeric streaming via numeric_enum_values_v */
template <typename enum_type>
concept numeric_io_enum =
    std::is_enum_v<enum_type> && (numeric_enum_values_v<enum_type>.size() > 0);

/**
 * @brief Every value of a contiguous enum from FIRST to LAST, for numeric_enum_values_v
 * @tparam FIRST The enumerator with the smallest value
 * @tparam LAST The enumerator with the largest value
 * @return The values FIRST, FIRST + 1, ..., LAST
 */
template <auto FIRST, auto LAST>
    requires std::is_enum_v<decltype(FIRST)> && std::is_same_v<decltype(FIRST), decltype(LAST)>
consteval auto numeric_enum_range() {
    using enum_type = decltype(FIRST);
    static_assert(std::to_underlying(FIRST) <= std::to_underlying(LAST));
    std::array<enum_type, std::to_underlying(LAST) - std::to_underlying(FIRST) + 1> values{};
    for(std::size_t pos = 0; pos < values.size(); ++pos) {
        values.at(pos) = static_cast<enum_type>(std::to_underlying(FIRST) + pos);
    }
    return values;
}

/**
 * @brief Writes an opted-in enum to a stream as its underlying numeric value
 * @param o The output stream to write to
 * @param x The enum value to be streamed out
 * @return A reference to the output stream
 */
template <numeric_io_enum enum_type>
std::ostream &operator<<(std::ostream &o, enum_type const &x) {
    // The wide intermediate keeps a std::uint8_t-based enum printing as a
    // number rather than as a single character
    o << static_cast<std::int64_t>(std::to_underlying(x));
    return o;
}

/**
 * @brief Reads an opted-in enum from a stream as its underlying numeric value. A number that is
 * none of the enum's values (see numeric_enum_values_v) fails the stream, as text does.
 * @param i The input stream to read from
 * @param x The enum value to be filled from the stream (unchanged if the stream fails)
 * @return A reference to the input stream
 */
template <numeric_io_enum enum_type>
std::istream &operator>>(std::istream &i, enum_type &x) {
    // Wide intermediate for the same reason as in operator<< (a std::uint8_t
    // would otherwise be read as a single character)
    std::int64_t value = 0;
    if(not(i >> value)) {
        return i;
    }
    for(enum_type const candidate : numeric_enum_values_v<enum_type>) {
        if(std::cmp_equal(value, std::to_underlying(candidate))) {
            x = candidate;
            return i;
        }
    }
    i.setstate(std::ios_base::failbit);
    return i;
}

/**
 * @brief The values of an opted-in enum for a message: "0, 1 or 2"
 * @tparam enum_type The enum whose values are listed (see numeric_enum_values_v)
 * @return The numeric values, separated by commas and a final "or"
 */
template <numeric_io_enum enum_type>
std::string numericEnumValueList() {
    auto const &values = numeric_enum_values_v<enum_type>;
    std::string text;
    for(std::size_t pos = 0; pos < values.size(); ++pos) {
        if(pos > 0) {
            text += (pos + 1 == values.size()) ? " or " : ", ";
        }
        text += std::to_string(static_cast<std::int64_t>(std::to_underlying(values.at(pos))));
    }
    return text;
}

/******************************************************************************/
/**
 * The names of an enum's values, written once, next to the enum: one pair of a value and its name
 * per value, specialized (in namespace Gem::Common, as numeric_enum_values_v) right after the
 * enum's definition. enumName() reads a value's name from the table and enumFromName() the value
 * of a name, so that no enum needs a function of its own that spells its names out again.
 *
 * The name is the text a value is known by where it is printed or read: mostly the enumerator's
 * own spelling, otherwise the word that files, scripts or the manual use for it. An enum has one
 * table; a sentence that describes a value in a message is not its name and stays with the
 * message.
 *
 * Checked at compile time wherever enumName() or enumFromName() is used: no value and no name
 * appears twice, and an enum that lists its values in numeric_enum_values_v names exactly these.
 *
 * @code
 * template <>
 * inline constexpr auto enum_names_v<sortOrder> = std::to_array<std::pair<sortOrder, std::string_view>>(
 *     {{sortOrder::LOWERISBETTER, "LOWERISBETTER"}, {sortOrder::HIGHERISBETTER, "HIGHERISBETTER"}}
 * );
 * @endcode
 */
template <typename enum_type>
inline constexpr auto enum_names_v = std::array<std::pair<enum_type, std::string_view>, 0>{};

/** @brief Satisfied by enum types whose values are named in enum_names_v */
template <typename enum_type>
concept named_enum = std::is_enum_v<enum_type> && (enum_names_v<enum_type>.size() > 0);

/**
 * @brief Whether the name table of an enum is complete and unambiguous (see enum_names_v)
 * @tparam enum_type An enum with a name table
 * @return true if no value and no name appears twice and, where numeric_enum_values_v lists the
 *         enum's values, the table names exactly these
 */
template <named_enum enum_type>
consteval bool enumNamesAreComplete() {
    auto const &names = enum_names_v<enum_type>;
    for(std::size_t pos = 0; pos < names.size(); ++pos) {
        for(std::size_t other = pos + 1; other < names.size(); ++other) {
            if(names.at(pos).first == names.at(other).first ||
               names.at(pos).second == names.at(other).second) {
                return false;
            }
        }
    }
    if constexpr(numeric_io_enum<enum_type>) {
        auto const &values = numeric_enum_values_v<enum_type>;
        if(values.size() != names.size()) {
            return false;
        }
        for(enum_type const value : values) {
            bool named = false;
            for(auto const &entry : names) {
                named = named || entry.first == value;
            }
            if(not named) {
                return false;
            }
        }
    }
    return true;
}

/**
 * @brief The name of an enum's value, from its table (see enum_names_v)
 * @param value The value
 * @return Its name
 * @throws gem_exception if the value has no name: a number cast to the enum that is none of its
 *         values
 */
template <named_enum enum_type>
[[nodiscard]] constexpr std::string_view enumName(enum_type value) {
    static_assert(
        enumNamesAreComplete<enum_type>(),
        "enum_names_v names a value twice, uses a name twice, or does not name exactly the values "
        "of numeric_enum_values_v"
    );
    for(auto const &[candidate, name] : enum_names_v<enum_type>) {
        if(candidate == value) {
            return name;
        }
    }
    throw gem_exception(
        g_error_streamer() << "Gem::Common::enumName(): the value "
                           << static_cast<std::int64_t>(std::to_underlying(value))
                           << " is none of the enum's values and has no name" << '\n'
    );
}

/**
 * @brief The value of an enum with the given name, from its table (see enum_names_v)
 * @tparam enum_type The enum
 * @param name A name, spelled exactly as in the table
 * @return The value, or nothing if no value has this name
 */
template <named_enum enum_type>
[[nodiscard]] constexpr std::optional<enum_type> enumFromName(std::string_view name) {
    static_assert(
        enumNamesAreComplete<enum_type>(),
        "enum_names_v names a value twice, uses a name twice, or does not name exactly the values "
        "of numeric_enum_values_v"
    );
    for(auto const &[value, candidate] : enum_names_v<enum_type>) {
        if(candidate == name) {
            return value;
        }
    }
    return std::nullopt;
}

