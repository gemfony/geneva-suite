// Tell Boost not to compile std::auto_ptr compatibility functions — std::auto_ptr
// was removed in C++17 and Geneva requires C++20.
#define BOOST_NO_AUTO_PTR

#include <boost/config.hpp>

/**
 * The current version of the Geneva library.
 *
 * The three component macros below are the single source of truth; GENEVA_VERSION
 * composes them into one monotonically comparable integer
 *   major * 10000 + minor * 100 + patch
 * so that e.g. 1.99.0 → 19900 and ordinary version tests such as
 *   #if GENEVA_VERSION >= 19900
 * work. Each component is a plain decimal literal (no leading zero), so no value is
 * ever silently reinterpreted as octal — the historical packed-literal form (e.g.
 * "019900") was an octal literal and, once a minor/patch digit reached 8 or 9 as it
 * has here, would have been an outright invalid octal literal.
 *
 * Keep in sync with VERSION_MAJOR / VERSION_MINOR / VERSION_PATCH / VERSION_SUFFIX in the
 * top-level CMakeLists.txt.
 * Note: FindGeneva.cmake parses the three component macros below to determine the
 * installed version.
 */
#define GENEVA_VERSION_MAJOR 1
#define GENEVA_VERSION_MINOR 99
#define GENEVA_VERSION_PATCH 0
/* The pre-release tag, INCLUDING its leading dash (e.g. "-beta1"); an empty string literal for a
 * final release. Appended to the human-facing GENEVA_VERSION_STRING (GModuleManifest.hpp); the
 * numeric GENEVA_VERSION below is unaffected. */
#define GENEVA_VERSION_PRERELEASE "-beta1"
#define GENEVA_VERSION (GENEVA_VERSION_MAJOR * 10000 + GENEVA_VERSION_MINOR * 100 + GENEVA_VERSION_PATCH)

/**
 * The minimum required Boost version, encoded as an integer.
 * Encoding: major(1 digit) + "0" + minor(2 digits) + "00"
 * Example:  1.91  →  "1" + "0" + "91" + "00"  =  109100
 *
 * Keep in sync with GENEVA_MIN_BOOST_VERSION in
 * CMakeModules/CommonGenevaBuild.cmake.
 */
#define MIN_BOOST_VERSION 109100

#if BOOST_VERSION < MIN_BOOST_VERSION
#error "Error: Boost should at least have version 1.91 !"
#endif /* BOOST_VERSION */

//-----------------------------------------------------------

/** @brief Returns x squared, evaluating its argument exactly once (the former GSQUARED
 *  macro evaluated it twice). Direct multiplication is faster than std::pow(x, 2)
 *  on g++.
 *
 *  @tparam T The type of the value to be squared (must support operator*)
 *  @param x The value to be squared; evaluated exactly once
 *  @return The product x * x, of whatever type x * x yields */
namespace Gem::Common {
template <typename T>
[[nodiscard]] constexpr auto gsquared(T const &x) -> decltype(x * x) {
    return x * x;
}
} // namespace Gem::Common

