/******************************************************************************/
/** A short identifier suitable for storage in a std::map */
const std::string GSwarmAlgorithm_PersonalityTraits::nickname = "swarm"; // NOLINT

/******************************************************************************/
/**
 * @brief The copy constructor
 *
 * @param cp A constant reference to another GSwarmAlgorithm_PersonalityTraits object to be copied
 */
GSwarmAlgorithm_PersonalityTraits::GSwarmAlgorithm_PersonalityTraits(
    const GSwarmAlgorithm_PersonalityTraits &cp
)
  : Gem::Common::GReflectiveInterfaceT<GSwarmAlgorithm_PersonalityTraits, GPersonalityTraits>(cp) {
    // The members are copied through localMembers_(); the personal best is deep-cloned. It is a bare
    // individual carrying no personality (registerPersonalBest() clears it), so there is no chain to break.
    Gem::Common::g_load_members(this->localMembers_(), cp.localMembers_());
}

/******************************************************************************/
/**
 * @brief The copy assignment. Copy-constructs and move-assigns the result, so it is as deep as the copy
 * constructor and states no member list of its own (the implicit assignment shared personal_best_).
 *
 * @param cp The traits to copy from
 * @return A reference to this object
 */
GSwarmAlgorithm_PersonalityTraits &
GSwarmAlgorithm_PersonalityTraits::operator=(const GSwarmAlgorithm_PersonalityTraits &cp) {
    if(this != &cp) {
        *this = GSwarmAlgorithm_PersonalityTraits(cp);
    }
    return *this;
}

